-- payment-service baseline (schema "payment"). Orders live in the backend; a
-- payment keeps an order id and owner snapshot. Card data is reduced to brand
-- and last four digits: the full number and the CVC are never stored.
CREATE TABLE payments (
    id uuid PRIMARY KEY,
    order_id bigint NOT NULL,
    username varchar(255) NOT NULL,
    status varchar(32) NOT NULL CHECK (status IN ('REQUIRES_ACTION', 'PROCESSING', 'CAPTURED', 'FAILED',
                                                  'PARTIALLY_REFUNDED', 'REFUNDED', 'VOIDED')),
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    refunded_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
    currency varchar(3) NOT NULL,
    card_brand varchar(16) NOT NULL CHECK (card_brand IN ('VISA', 'MASTERCARD', 'AMEX', 'OTHER')),
    card_last4 varchar(4) NOT NULL,
    failure_code varchar(32),
    failure_message varchar(255),
    -- Simulated provider outcome of a PROCESSING payment and when it settles.
    settlement varchar(16) CHECK (settlement IN ('CAPTURE', 'TIMEOUT')),
    settle_at timestamp(6),
    version bigint NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    CONSTRAINT ck_payments_refund_within_amount CHECK (refunded_amount <= amount)
);
CREATE INDEX idx_payments_order ON payments(order_id, created_at);
CREATE INDEX idx_payments_status ON payments(status, created_at);
CREATE INDEX idx_payments_settle ON payments(status, settle_at);

-- Idempotency-Key per caller: the request fingerprint is an HMAC of the body
-- (never the card number itself), so a replay can be told from a conflicting reuse.
CREATE TABLE payment_idempotency_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL,
    idempotency_key varchar(64) NOT NULL,
    request_hash varchar(64) NOT NULL,
    payment_id uuid NOT NULL REFERENCES payments(id),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_payment_idempotency_key UNIQUE (username, idempotency_key)
);

-- Signed result notifications for the backend, written in the same transaction
-- as the payment change and retried with backoff. request_id is not unique:
-- the duplicate-notification test card deliberately enqueues one result twice.
CREATE TABLE payment_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL,
    payment_id uuid NOT NULL REFERENCES payments(id),
    order_id bigint NOT NULL,
    payload varchar(2000) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamp(6) NOT NULL,
    sent_at timestamp(6),
    last_error varchar(500),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_payment_outbox_due ON payment_outbox(sent_at, next_attempt_at);
CREATE INDEX idx_payment_outbox_request ON payment_outbox(request_id);

-- Card refunds booked by the backend; request_id makes them idempotent.
CREATE TABLE refunds (
    id uuid PRIMARY KEY,
    request_id uuid NOT NULL,
    payment_id uuid NOT NULL REFERENCES payments(id),
    order_id bigint NOT NULL,
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    reason varchar(255),
    payment_status varchar(32) NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_refunds_request UNIQUE (request_id)
);
CREATE INDEX idx_refunds_payment ON refunds(payment_id);
